// Builds src/styles/_generated-tokens.scss from the W3C design tokens in src/design-tokens/ff.tokens.json.
// `node scripts/build-design-tokens.mjs` writes the file, `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(root, 'src/design-tokens/ff.tokens.json');
const TARGET = resolve(root, 'src/styles/_generated-tokens.scss');

/** Flattens a token group into `[name, value]` pairs; `$`-prefixed keys are metadata. */
function leaves(group, prefix = []) {
  return Object.entries(group).flatMap(([key, node]) => {
    if (key.startsWith('$')) {
      return [];
    }
    return '$value' in node
      ? [[[...prefix, key].join('-'), node.$value]]
      : leaves(node, [...prefix, key]);
  });
}

function block(selector, entries, indent = '') {
  const lines = entries.map(([name, value]) => `${indent}  --ff-${name}: ${value};`);
  return [`${indent}${selector} {`, ...lines, `${indent}}`].join('\n');
}

export function buildTokensScss(tokens) {
  const colors = (mode) => leaves(tokens.color[mode]).map(([n, v]) => [`color-${n}`, v]);
  const shadows = (mode) => leaves(tokens.shadow[mode]).map(([n, v]) => [`shadow-${n}`, v]);
  const prefixed = (group, prefix) => leaves(tokens[group]).map(([n, v]) => [`${prefix}-${n}`, v]);
  const density = (name) => leaves(tokens.density[name]).map(([n, v]) => [`density-${n}`, v]);

  const shared = [
    ...prefixed('space', 'space'),
    ...prefixed('radius', 'radius'),
    ...leaves(tokens.font.family).map(([n, v]) => [`font-family-${n}`, v]),
    ...leaves(tokens.font.size).map(([n, v]) => [`font-size-${n}`, v]),
    ...prefixed('a11y', 'a11y'),
  ];

  return [
    '// GENERATED by scripts/build-design-tokens.mjs from src/design-tokens/ff.tokens.json. Do not edit by hand.',
    '// The default theme is light and the default density is comfortable; ThemeService sets data-theme and data-density.',
    '',
    ':root {',
    '  color-scheme: light;',
    ...[...colors('light'), ...shadows('light'), ...shared, ...density('comfortable')].map(
      ([n, v]) => `  --ff-${n}: ${v};`,
    ),
    '}',
    '',
    block("[data-theme='dark']", [...colors('dark'), ...shadows('dark')]).replace(
      '{\n',
      '{\n  color-scheme: dark;\n',
    ),
    '',
    ...['compact', 'comfortable', 'spacious'].flatMap((name) => [
      block(`[data-density='${name}']`, density(name)),
      '',
    ]),
  ].join('\n');
}

const tokens = JSON.parse(readFileSync(SOURCE, 'utf8'));
const output = buildTokensScss(tokens);

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const current = readFileSync(TARGET, 'utf8');
    // A Windows checkout may hold CRLF; the content is what counts.
    if (current.replaceAll('\r\n', '\n') !== output) {
      console.error('src/styles/_generated-tokens.scss is stale: run `pnpm tokens:build`.');
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, output, 'utf8');
    console.log(`Wrote ${TARGET}`);
  }
}
