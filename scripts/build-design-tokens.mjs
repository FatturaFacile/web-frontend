const clamp255 = (n) => Math.min(255, Math.max(0, Math.round(n)));
const hex2 = (n) => clamp255(n).toString(16).padStart(2, '0').toUpperCase();

/** Parses `#rgb`, `#rgba`, `#rrggbb`, `#rrggbbaa`, `rgb()` and `rgba()` into `{ r, g, b, a }` (a in 0..1), else null. */
export function parseCssColor(value) {
  const v = String(value).trim().toLowerCase();
  const hex = /^#([0-9a-f]{3,8})$/.exec(v);
  if (hex) {
    let h = hex[1];
    if (h.length === 3 || h.length === 4) {
      h = [...h].map((c) => c + c).join('');
    }
    if (h.length !== 6 && h.length !== 8) {
      return null;
    }
    return {
      r: parseInt(h.slice(0, 2), 16),
      g: parseInt(h.slice(2, 4), 16),
      b: parseInt(h.slice(4, 6), 16),
      a: h.length === 8 ? Math.round((parseInt(h.slice(6, 8), 16) / 255) * 1000) / 1000 : 1,
    };
  }
  const fn = /^rgba?\(\s*([^)]+)\)$/.exec(v);
  if (fn) {
    const parts = fn[1].split(/[\s,/]+/).filter(Boolean);
    if (parts.length < 3 || parts.length > 4) {
      return null;
    }
    const channel = (p) => (p.endsWith('%') ? (parseFloat(p) / 100) * 255 : parseFloat(p));
    const [r, g, b] = parts.slice(0, 3).map(channel);
    const a =
      parts[3] === undefined
        ? 1
        : parts[3].endsWith('%')
          ? parseFloat(parts[3]) / 100
          : parseFloat(parts[3]);
    if ([r, g, b, a].some(Number.isNaN)) {
      return null;
    }
    return { r: clamp255(r), g: clamp255(g), b: clamp255(b), a: Math.min(1, Math.max(0, a)) };
  }
  return null;
}

/** `#rrggbb`, or `#rrggbbaa` when not opaque (CSS order, lower case). Platform-neutral form. */
export function colorToCssHex(c) {
  const base = `#${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}`.toLowerCase();
  return c.a >= 1 ? base : `${base}${hex2(c.a * 255).toLowerCase()}`;
}

/** Flutter `Color(0xAARRGGBB)`. */
export function colorToDart(c) {
  return `Color(0x${hex2(c.a * 255)}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)})`;
}

/** WPF colour literal: `#AARRGGBB` (always with alpha so the literal is unambiguous). */
export function colorToXaml(c) {
  return `#${hex2(c.a * 255)}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}`;
}

/** `14px`, `0.875rem`, `1.5em`, `0` -> number of logical pixels (1rem = 1em = 16px); null for anything else. */
export function parsePx(value) {
  const m = /^(-?\d*\.?\d+)\s*(px|rem|em)?$/.exec(String(value).trim().toLowerCase());
  if (!m) {
    return null;
  }
  const n = parseFloat(m[1]);
  return m[2] === 'rem' || m[2] === 'em' ? n * 16 : n;
}

const GENERIC_FAMILIES = new Set([
  'system-ui',
  '-apple-system',
  'blinkmacsystemfont',
  'ui-monospace',
  'ui-sans-serif',
  'ui-serif',
  'sans-serif',
  'serif',
  'monospace',
  'sfmono-regular',
  'menlo',
]);

/** Splits a CSS font stack, drops quotes and CSS-only generic names: `"'Inter', system-ui, Roboto"` -> `['Inter','Roboto']`. */
export function parseFontStack(value) {
  return String(value)
    .split(',')
    .map((f) => f.trim().replace(/^['"]|['"]$/g, ''))
    .filter((f) => f && !GENERIC_FAMILIES.has(f.toLowerCase()));
}

const words = (name) => name.split(/[^a-zA-Z0-9]+/).filter(Boolean);
const upperFirst = (w) => w.charAt(0).toUpperCase() + w.slice(1);

/** `surface-alt` -> `SurfaceAlt`; `2xl` -> `2xl`. */
export const pascal = (name) => words(name).map(upperFirst).join('');

/** `surface-alt` -> `surfaceAlt`; names starting with a digit get `prefix`: (`2xl`, `size`) -> `size2xl`. */
export function camel(name, prefix = '') {
  const ws = words(name);
  const joined = ws.map((w, i) => (i === 0 ? w.toLowerCase() : upperFirst(w))).join('');
  return /^\d/.test(joined) ? `${prefix}${upperFirst(joined)}` : joined;
}

