// Token model shared by every platform output.
// ---------------------------------------------------------------------------------------------------------------------

function colorMap(group) {
  const out = {};
  for (const [name, value] of leaves(group)) {
    const parsed = parseCssColor(value);
    if (!parsed) {
      throw new Error(`Colour token "${name}" has an unsupported value: ${value}`);
    }
    out[name] = parsed;
  }
  return out;
}

function pxMap(group) {
  const out = {};
  for (const [name, value] of leaves(group)) {
    const n = parsePx(value);
    if (n === null) {
      throw new Error(`Dimension token "${name}" has an unsupported value: ${value}`);
    }
    out[name] = n;
  }
  return out;
}

/** Normalised, platform-neutral model: colours as RGBA, dimensions as numbers, shadows/font stacks kept as text. */
export function buildModel(tokens) {
  const densities = {};
  for (const name of Object.keys(tokens.density).filter((k) => !k.startsWith('$'))) {
    densities[name] = pxMap(tokens.density[name]);
  }
  return {
    colors: { light: colorMap(tokens.color.light), dark: colorMap(tokens.color.dark) },
    space: pxMap(tokens.space),
    radius: pxMap(tokens.radius),
    fontSize: pxMap(tokens.font.size),
    fontFamily: Object.fromEntries(
      leaves(tokens.font.family).map(([n, v]) => [n, parseFontStack(v)]),
    ),
    a11y: pxMap(tokens.a11y),
    density: densities,
    // Box shadows have no 1:1 mapping in Flutter/WPF: kept as CSS text for reference only.
    shadow: {
      light: Object.fromEntries(leaves(tokens.shadow.light)),
      dark: Object.fromEntries(leaves(tokens.shadow.dark)),
    },
  };
}

const num = (n) => (Number.isInteger(n) ? String(n) : String(Math.round(n * 1000) / 1000));
const entries = (o) => Object.entries(o);

export function buildFlatJson(model) {
  const hexes = (m) => Object.fromEntries(entries(m).map(([k, c]) => [k, colorToCssHex(c)]));
  return `${JSON.stringify(
    {
      $description:
        'GENERATED by scripts/build-design-tokens.mjs from ff.tokens.json. Platform-neutral: colours are CSS hex (#rrggbb or #rrggbbaa), dimensions are logical pixels. Do not edit by hand.',
      color: { light: hexes(model.colors.light), dark: hexes(model.colors.dark) },
      space: model.space,
      radius: model.radius,
      fontSize: model.fontSize,
      fontFamily: model.fontFamily,
      a11y: model.a11y,
      density: model.density,
      shadow: model.shadow,
    },
    null,
    2,
  )}\n`;
}

// ------------------------------------------------------------------ Flutter

const dartDouble = (n) => (Number.isInteger(n) ? `${n}.0` : num(n));

export function buildDart(model) {
  const names = Object.keys(model.colors.light);
  const has = (n) => names.includes(n);
  const field = (n) => camel(n);
  const lines = [];
  const p = (s = '') => lines.push(s);

  p('// GENERATED by scripts/build-design-tokens.mjs from ff.tokens.json. Do not edit by hand.');
  p('// Copy into the Flutter app (e.g. lib/design/ff_tokens.dart) with `pnpm tokens:sync`.');
  p('// ignore_for_file: public_member_api_docs, lines_longer_than_80_chars');
  p("import 'package:flutter/material.dart';");
  p();
  p(
    '/// Semantic colours, one const instance per theme. Registered on `ThemeData.extensions` by [ffThemeData].',
  );
  p('@immutable');
  p('class FfColors extends ThemeExtension<FfColors> {');
  p('  const FfColors({');
  for (const n of names) p(`    required this.${field(n)},`);
  p('  });');
  p();
  for (const n of names) p(`  final Color ${field(n)};`);
  p();
  for (const mode of ['light', 'dark']) {
    p(`  static const FfColors ${mode} = FfColors(`);
    for (const n of names) p(`    ${field(n)}: ${colorToDart(model.colors[mode][n])},`);
    p('  );');
    p();
  }
  p('  @override');
  p('  FfColors copyWith({');
  for (const n of names) p(`    Color? ${field(n)},`);
  p('  }) {');
  p('    return FfColors(');
  for (const n of names) p(`      ${field(n)}: ${field(n)} ?? this.${field(n)},`);
  p('    );');
  p('  }');
  p();
  p('  @override');
  p('  FfColors lerp(ThemeExtension<FfColors>? other, double t) {');
  p('    if (other is! FfColors) return this;');
  p('    return FfColors(');
  for (const n of names) p(`      ${field(n)}: Color.lerp(${field(n)}, other.${field(n)}, t)!,`);
  p('    );');
  p('  }');
  p('}');
  p();

  p('/// Spacing scale (logical pixels).');
  p('abstract final class FfSpace {');
  for (const [n, v] of entries(model.space))
    p(`  static const double ${camel(n, 'space')} = ${dartDouble(v)};`);
  p('}');
  p();
  p('/// Corner radii (logical pixels).');
  p('abstract final class FfRadius {');
  for (const [n, v] of entries(model.radius))
    p(`  static const double ${camel(n)} = ${dartDouble(v)};`);
  p('}');
  p();
  p(
    '/// Type scale and families. Family lists are in preference order; the first installed one wins.',
  );
  p('abstract final class FfFont {');
  for (const [n, v] of entries(model.fontSize))
    p(`  static const double ${camel(n, 'size')} = ${dartDouble(v)};`);
  for (const [n, v] of entries(model.fontFamily)) {
    p(`  static const String ${camel(n, 'family')} = '${v[0] ?? ''}';`);
    p(
      `  static const List<String> ${camel(n, 'family')}Fallback = [${v
        .slice(1)
        .map((f) => `'${f}'`)
        .join(', ')}];`,
    );
  }
  p('}');
  p();
  p('/// Accessibility minimums (WCAG 2.2 AA): target size and focus ring.');
  p('abstract final class FfA11y {');
  for (const [n, v] of entries(model.a11y))
    p(`  static const double ${camel(n)} = ${dartDouble(v)};`);
  p('}');
  p();

  const densityNames = Object.keys(model.density);
  const densityFields = Object.keys(model.density[densityNames[0]]);
  p('/// One density preset (compact, comfortable, spacious).');
  p('@immutable');
  p('class FfDensity {');
  p('  const FfDensity({');
  for (const n of densityFields) p(`    required this.${camel(n)},`);
  p('  });');
  for (const n of densityFields) p(`  final double ${camel(n)};`);
  p();
  for (const d of densityNames) {
    p(`  static const FfDensity ${camel(d)} = FfDensity(`);
    for (const n of densityFields) p(`    ${camel(n)}: ${dartDouble(model.density[d][n])},`);
    p('  );');
  }
  p('}');
  p();

  const pick = (n, fallback) => (has(n) ? `colors.${field(n)}` : fallback);
  p('/// Builds a Material 3 [ThemeData] from the tokens. The default density is comfortable.');
  p('ThemeData ffThemeData({');
  p('  Brightness brightness = Brightness.light,');
  p('  FfDensity density = FfDensity.comfortable,');
  p('}) {');
  p('  final colors = brightness == Brightness.dark ? FfColors.dark : FfColors.light;');
  p('  final scheme = ColorScheme(');
  p('    brightness: brightness,');
  p(`    primary: ${pick('primary', 'Colors.teal')},`);
  p(`    onPrimary: ${pick('on-primary', 'Colors.white')},`);
  p(`    secondary: ${pick('accent', pick('primary', 'Colors.amber'))},`);
  p(`    onSecondary: ${pick('on-accent', 'Colors.white')},`);
  p(`    error: ${pick('danger', 'Colors.red')},`);
  p(`    onError: ${pick('on-primary', 'Colors.white')},`);
  p(`    surface: ${pick('surface', 'Colors.white')},`);
  p(`    onSurface: ${pick('text', 'Colors.black')},`);
  p(`    outline: ${pick('border-input', pick('border', 'Colors.grey'))},`);
  p(`    outlineVariant: ${pick('border-subtle', pick('border', 'Colors.grey'))},`);
  p(`    surfaceContainerHighest: ${pick('surface-alt', pick('surface', 'Colors.white'))},`);
  p('  );');
  p('  return ThemeData(');
  p('    useMaterial3: true,');
  p('    colorScheme: scheme,');
  p(`    scaffoldBackgroundColor: ${pick('bg', pick('surface', 'Colors.white'))},`);
  p(`    focusColor: ${pick('focus', pick('primary', 'Colors.teal'))},`);
  p('    fontFamily: FfFont.familyBase,');
  p('    fontFamilyFallback: FfFont.familyBaseFallback,');
  p(
    '    visualDensity: density == FfDensity.compact ? VisualDensity.compact : VisualDensity.standard,',
  );
  p('    materialTapTargetSize: MaterialTapTargetSize.padded,');
  p('    extensions: <ThemeExtension<dynamic>>[colors],');
  p('  );');
  p('}');
  p();
  return lines.join('\n');
}

// ------------------------------------------------------------------ WPF

const XAML_NS =
  'xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml" xmlns:sys="clr-namespace:System;assembly=mscorlib"';

const xamlDictionary = (comment, body) =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- GENERATED by scripts/build-design-tokens.mjs from ff.tokens.json. Do not edit by hand. ${comment} -->`,
    `<ResourceDictionary ${XAML_NS}>`,
    ...body.map((l) => `  ${l}`),
    '</ResourceDictionary>',
    '',
  ].join('\n');

export function buildXamlColors(model, mode) {
  const body = [];
  for (const [n, c] of entries(model.colors[mode])) {
    body.push(`<Color x:Key="Ff.Color.${pascal(n)}">${colorToXaml(c)}</Color>`);
  }
  for (const [n, c] of entries(model.colors[mode])) {
    body.push(`<SolidColorBrush x:Key="Ff.Brush.${pascal(n)}" Color="${colorToXaml(c)}" />`);
  }
  return xamlDictionary(
    'Merge one theme dictionary and swap it at runtime; reference brushes with DynamicResource.',
    body,
  );
}

export function buildXamlSpacing(model) {
  const dbl = (key, v) => `<sys:Double x:Key="${key}">${num(v)}</sys:Double>`;
  const body = [];
  for (const [n, v] of entries(model.space)) {
    body.push(dbl(`Ff.Space.${pascal(n)}`, v));
    body.push(`<Thickness x:Key="Ff.Thickness.${pascal(n)}">${num(v)}</Thickness>`);
  }
  for (const [n, v] of entries(model.radius)) {
    body.push(`<CornerRadius x:Key="Ff.Radius.${pascal(n)}">${num(v)}</CornerRadius>`);
  }
  for (const [n, v] of entries(model.fontSize)) body.push(dbl(`Ff.FontSize.${pascal(n)}`, v));
  for (const [n, v] of entries(model.fontFamily)) {
    body.push(`<FontFamily x:Key="Ff.Font.${pascal(n)}">${v.join(', ')}</FontFamily>`);
  }
  for (const [n, v] of entries(model.a11y)) body.push(dbl(`Ff.A11y.${pascal(n)}`, v));
  for (const [d, group] of entries(model.density)) {
    for (const [n, v] of entries(group)) body.push(dbl(`Ff.Density.${pascal(d)}.${pascal(n)}`, v));
  }
  return xamlDictionary(
    'Spacing, radius, type, accessibility minimums and the three density presets.',
    body,
  );
}

/** Every generated file, keyed by repo-relative path. */
export function buildAllOutputs(tokens) {
  const model = buildModel(tokens);
  return {
    'src/styles/_generated-tokens.scss': buildTokensScss(tokens),
    'src/design-tokens/dist/ff.tokens.flat.json': buildFlatJson(model),
    'src/design-tokens/dist/ff_tokens.dart': buildDart(model),
    'src/design-tokens/dist/FfTokens.Light.xaml': buildXamlColors(model, 'light'),
    'src/design-tokens/dist/FfTokens.Dark.xaml': buildXamlColors(model, 'dark'),
    'src/design-tokens/dist/FfTokens.Spacing.xaml': buildXamlSpacing(model),
  };
}

/** Where `--sync` copies each dist file in the sibling repositories (sibling folder, path inside it). */
export const SYNC_TARGETS = {
  'ff_tokens.dart': ['mobile', 'lib/design/ff_tokens.dart'],
  'FfTokens.Light.xaml': ['desktop', 'src/FatturaFacile.Wpf/Themes/FfTokens.Light.xaml'],
  'FfTokens.Dark.xaml': ['desktop', 'src/FatturaFacile.Wpf/Themes/FfTokens.Dark.xaml'],
  'FfTokens.Spacing.xaml': ['desktop', 'src/FatturaFacile.Wpf/Themes/FfTokens.Spacing.xaml'],
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const outputs = buildAllOutputs(tokens);

  if (process.argv.includes('--check')) {
    const stale = Object.entries(outputs).filter(([file, content]) => {
      const path = resolve(root, file);
      // A Windows checkout may hold CRLF; the content is what counts.
      return !existsSync(path) || readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== content;
    });
    if (stale.length > 0) {
      console.error(
        `Stale or missing generated token files: ${stale.map(([f]) => f).join(', ')}. Run \`pnpm tokens:build\`.`,
      );
      process.exit(1);
    }
  } else {
    mkdirSync(DIST, { recursive: true });
    for (const [file, content] of Object.entries(outputs)) {
      writeFileSync(resolve(root, file), content, 'utf8');
      console.log(`Wrote ${file}`);
    }
    if (process.argv.includes('--sync')) {
      // Copies the generated Flutter/WPF files into the sibling checkouts (../mobile, ../desktop). Nothing is committed.
      for (const [name, [repo, relative]] of Object.entries(SYNC_TARGETS)) {
        const target = resolve(root, '..', repo, relative);
        mkdirSync(dirname(target), { recursive: true });
        copyFileSync(resolve(DIST, name), target);
        console.log(`Synced ${name} -> ${target}`);
      }
    }
  }
}
