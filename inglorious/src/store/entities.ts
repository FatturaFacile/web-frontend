/**
 * A list page's entity. Its keys follow one scheme: `<SECTION>.TITLE`,
 * `.SUBTITLE` and `.CARD_TITLE`.
 */
function listPage(
  type: ListPageTypeName,
  section: string,
  columns: [id: string, title: string][],
): ListPageEntity {
  return {
    type,
    titleKey: `${section}.TITLE`,
    subtitleKey: `${section}.SUBTITLE`,
    cardTitleKey: `${section}.CARD_TITLE`,
    columns: columns.map(([id, title]): ListColumn => ({ id, title })),
    rows: [],
    isLoading: false,
    failure: null,
  } as ListPageEntity
}

